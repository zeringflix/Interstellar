"""Reads blender/out/<Vehicle>.blend and writes roblox/src/shared/VehicleMeshInfo.luau:
for every exported object, the centre of its bounding box (Roblox axes, relative to the vehicle
origin) and its size. The game uses this to seat each imported MeshPart exactly."""
import json
import os

import bpy
from mathutils import Vector

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = json.load(open(os.path.join(HERE, "vehicles.json")))
lines = ["--!nonstrict", "-- GENERATED by blender/export_mesh_info.py - do not edit.",
         "-- [objectName] = { centreX, centreY, centreZ, sizeX, sizeY, sizeZ } in studs, Roblox axes, vehicle origin on the ground.", "return {"]
report = {}
for key in SPEC["order"]:
    path = os.path.join(HERE, "out", key + ".blend")
    if not os.path.exists(path):
        continue
    bpy.ops.wm.open_mainfile(filepath=path)
    lines.append("\t%s = {" % key)
    report[key] = {}
    for ob in sorted(bpy.data.objects, key=lambda o: o.name):
        if ob.type != "MESH" or not ob.name.startswith(key + "_"):
            continue
        pts = [ob.matrix_world @ Vector(c) for c in ob.bound_box]
        lo = Vector([min(p[i] for p in pts) for i in range(3)])
        hi = Vector([max(p[i] for p in pts) for i in range(3)])
        c, s = (lo + hi) / 2, hi - lo
        tris = sum(len(p.vertices) - 2 for p in ob.data.polygons)
        # Blender (x, y, z) -> Roblox (x, z, -y)
        lines.append("\t\t%s = { %.3f, %.3f, %.3f, %.3f, %.3f, %.3f }," % (ob.name, c.x, c.z, -c.y, max(s.x, 0.05), max(s.z, 0.05), max(s.y, 0.05)))
        report[key][ob.name] = tris
    lines.append("\t},")
lines.append("}")
out = os.path.join(HERE, "..", "roblox", "src", "shared", "VehicleMeshInfo.luau")
open(out, "w").write("\n".join(lines) + "\n")
json.dump(report, open(os.path.join(HERE, "out", "build_stats.json"), "w"), indent=1)
over = [(k, n, t) for k, d in report.items() for n, t in d.items() if t > 20000]
print("wrote", out, "| vehicles:", len(report), "| objects over 20k tris:", over)
